/**
 * @file icons.h
 * @brief Значки интерфейса, нарисованные, а не набранные шрифтом.
 *
 * Раньше это были символы Unicode - «☎», «⋮», скрепка. Выглядит просто, пока
 * не окажется, что нужного знака в системном шрифте нет: тогда пользователь
 * видит пустой квадрат, и ровно так на этой машине выглядели скрепка и
 * кнопка отправки. Знак, которого нет, ничем не заменить - поэтому рисуем
 * сами, тем же цветом, что и остальной интерфейс.
 */
#ifndef FEAR_GUI_ICONS_H
#define FEAR_GUI_ICONS_H

#include <QColor>
#include <QIcon>

namespace fear {

enum class Glyph {
    Phone,      ///< аудиозвонок
    Video,      ///< видеозвонок
    More,       ///< три точки
    Attach,     ///< скрепка
    Send,       ///< стрелка отправки
    Menu,       ///< три полосы
    Plus,       ///< новая комната
    Search,     ///< лупа
    Smile,      ///< выбор эмодзи
};

/** Значок @p g цвета @p color размером @p px точек. */
QIcon icon(Glyph g, const QColor &color, int px = 20);

} // namespace fear

#endif
