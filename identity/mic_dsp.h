/**
 * @file mic_dsp.h
 * @brief Обработка сигнала с микрофона: чувствительность и подавление шума
 *
 * Стоит между захватом и кодировщиком, работает на кадре PCM на месте.
 *
 * Честно о том, что это такое. Здесь не спектральное шумоподавление: шум
 * из-под голоса оно не вычитает, и пока человек говорит, фон слышен таким,
 * какой он есть. Здесь фильтр нижних частот, ворота по громкости и
 * усиление - то есть уходит ровно то, что слышно в паузах: гул, шипение,
 * вентилятор, улица за окном. На слух собеседника это и есть основная
 * разница, потому что пауз в разговоре больше, чем речи.
 *
 * Настоящее подавление потребовало бы отдельной библиотеки (speexdsp,
 * RNNoise) в каждой из четырёх сборок, включая Windows, где зависимости
 * лежат собранными заранее. Это отдельная работа, а не строчка в CMake.
 */

#ifndef MIC_DSP_H
#define MIC_DSP_H

#include <stddef.h>
#include <stdint.h>

/** Насколько сильно давить фон. */
typedef enum {
    MIC_NS_OFF = 0,   /**< не трогать вовсе */
    MIC_NS_LOW,       /**< убрать явный гул, оставить дыхание комнаты */
    MIC_NS_MEDIUM,    /**< обычный выбор */
    MIC_NS_HIGH,      /**< шумное место; тихую речь может подрезать */
} mic_ns_level_t;

/** Состояние обработки. Заводится на поток, живёт весь звонок. */
typedef struct {
    /* настройки */
    float          gain;        /**< линейный множитель чувствительности */
    mic_ns_level_t ns;
    float          hp_a;        /**< коэффициент фильтра верхних частот */

    /* состояние */
    float hp_x1, hp_y1;         /**< память фильтра */
    float noise_floor;          /**< оценка уровня фона, RMS */
    float gate;                 /**< нынешнее ослабление, 0..1 */
    int   primed;               /**< успела ли набраться оценка фона */
} mic_dsp_t;

/**
 * @param gain_db чувствительность в децибелах: 0 - как есть, +6 - вдвое
 *                громче, -6 - вдвое тише. Разумный предел ±24.
 * @param ns      насколько давить фон
 * @param rate    частота дискретизации
 */
void mic_dsp_init(mic_dsp_t *d, float gain_db, mic_ns_level_t ns, int rate);

/** Обработать кадр на месте. @p n - число отсчётов (моно). */
void mic_dsp_process(mic_dsp_t *d, int16_t *pcm, size_t n);

/** Разобрать имя уровня: off/low/medium/high. -1 если имя незнакомо. */
int mic_ns_from_string(const char *s, mic_ns_level_t *out);

#endif /* MIC_DSP_H */
